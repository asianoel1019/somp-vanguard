require('../helpers/setupEnv');
const test = require('node:test');
const assert = require('node:assert/strict');
const store = require('../../lib/agent/conversationStore');
const { createRateLimiter } = require('../../lib/agent/rateLimiter');

const alice = { username: 'Alice', domain: 'CORP' };
const bob = { username: 'bob', domain: 'corp' };
const t0 = new Date('2026-10-08T00:00:00.000Z');
const at = (min) => new Date(t0.getTime() + min * 60000);

test('userKey is lowercase, filesystem-safe and collision-free', () => {
    assert.equal(store.userKey(alice), 'alice@corp');
    assert.match(store.userKey({ username: 'a/b c', domain: '' }), /^a_b_c@local-[0-9a-f]{8}$/);
    assert.notEqual(store.userKey({ username: 'a/b', domain: 'corp' }), store.userKey({ username: 'a_b', domain: 'corp' }));
    assert.equal(store.userKey({ username: 'a_b', domain: 'corp' }), 'a_b@corp');
});

test('appendTurn creates a conversation with the given id and title', () => {
    const id = store.newConversationId();
    assert.match(id, /^conv-[0-9a-f-]{12}$/);
    const conv = store.appendTurn(alice, { conversationId: id, question: '為什麼 web-03 的 CPU 一直很高？請幫我看看最近的狀況', answer: '結論…', steps: [{ id: 's1', tool: 'find_host' }], suggestions: [] }, at(0));
    assert.equal(conv.id, id);
    assert.equal(conv.title, '為什麼 web-03 的 CPU 一直很高？請幫我看看最近的狀況'.slice(0, 40));
    assert.equal(conv.messages.length, 2);
    assert.equal(conv.messages[1].steps[0].tool, 'find_host');
});

test('follow-up turns append to the same conversation; list is newest first', () => {
    const [first] = store.listConversations(alice, at(1));
    store.appendTurn(alice, { conversationId: first.id, question: '那記憶體呢？', answer: '正常' }, at(2));
    const other = store.appendTurn(alice, { conversationId: store.newConversationId(), question: '第二個對話', answer: 'ok' }, at(3));
    const list = store.listConversations(alice, at(4));
    assert.deepEqual(list.map(c => c.id), [other.id, first.id]);
    assert.equal(store.getConversation(alice, first.id, at(4)).messages.length, 4);
});

test('conversations are private per user', () => {
    const [first] = store.listConversations(alice, at(5));
    assert.equal(store.getConversation(bob, first.id, at(5)), null);
    assert.deepEqual(store.listConversations(bob, at(5)), []);
});

test('historyForModel drops errored turns and keeps role/content only', () => {
    const conv = store.appendTurn(bob, { conversationId: store.newConversationId(), question: 'q1', answer: '', error: 'timeout' }, at(6));
    store.appendTurn(bob, { conversationId: conv.id, question: 'q2', answer: 'a2' }, at(7));
    const h = store.historyForModel(store.getConversation(bob, conv.id, at(8)));
    assert.deepEqual(h, [{ role: 'user', content: 'q1' }, { role: 'user', content: 'q2' }, { role: 'assistant', content: 'a2' }]);
    assert.deepEqual(store.historyForModel(null), []);
});

test('retention: older than 30 days are dropped; max 50 kept', () => {
    const user = { username: 'carol', domain: 'corp' };
    store.appendTurn(user, { conversationId: store.newConversationId(), question: 'old', answer: 'x' }, at(0));
    for (let i = 1; i <= 55; i++) store.appendTurn(user, { conversationId: store.newConversationId(), question: `c${i}`, answer: 'x' }, at(60 * 24 * 31 + i));
    const list = store.listConversations(user, at(60 * 24 * 31 + 100));
    assert.equal(list.length, 50);
    assert.ok(!list.some(c => c.title === 'old'));
    assert.equal(list[0].title, 'c55');
});

test('deleteConversation removes only own conversation', () => {
    const conv = store.appendTurn(bob, { conversationId: store.newConversationId(), question: 'del me', answer: 'x' }, at(9));
    assert.equal(store.deleteConversation(alice, conv.id), false);
    assert.equal(store.deleteConversation(bob, conv.id), true);
    assert.equal(store.getConversation(bob, conv.id, at(10)), null);
});

test('rate limiter: one at a time and N per hour', () => {
    const rl = createRateLimiter();
    const base = 1_000_000;
    assert.deepEqual(rl.tryStart('u', 2, base), { ok: true });
    assert.deepEqual(rl.tryStart('u', 2, base + 1), { ok: false, reason: 'busy' });
    rl.finish('u');
    assert.deepEqual(rl.tryStart('u', 2, base + 2), { ok: true });
    rl.finish('u');
    const limited = rl.tryStart('u', 2, base + 3);
    assert.equal(limited.reason, 'rate');
    assert.equal(limited.retryAfterSec, 3600);
    assert.deepEqual(rl.tryStart('u', 2, base + 3600 * 1000 + 1), { ok: true });
    assert.deepEqual(rl.tryStart('other', 2, base), { ok: true });
});

test('appendTurn ignores ids that were not generated by the store', () => {
    const conv = store.appendTurn(alice, { conversationId: '../../evil', question: 'x', answer: 'y' }, at(11));
    assert.match(conv.id, /^conv-[0-9a-f-]{12}$/);
    assert.notEqual(conv.id, '../../evil');
});

test('a conversation keeps at most 100 messages (newest kept)', () => {
    const user = { username: 'dave', domain: 'corp' };
    const id = store.newConversationId();
    for (let i = 0; i < 60; i++) store.appendTurn(user, { conversationId: id, question: `q${i}`, answer: `a${i}` }, at(20 + i));
    const conv = store.getConversation(user, id, at(100));
    assert.equal(conv.messages.length, 100);
    assert.equal(conv.messages[0].content, 'q10');
    assert.equal(conv.messages[99].content, 'a59');
});

test('appendTurn uses an explicit title but stores the full question', () => {
    const question = '<alert_data>\nX\n</alert_data>\n\nhello';
    const conv = store.appendTurn(alice, { question, title: 'hello', answer: 'a' }, at(50));
    assert.equal(conv.title, 'hello');
    assert.equal(conv.messages[0].content, question);
});
