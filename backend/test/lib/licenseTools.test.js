test('first use: an existing registry is backed up and imported once, then regenerated', (t) => {
    const { dir, reg, run } = setup(t, 'kimp');
    const row = (o) => core.registryRow({ licenseId: 'L-2025-0001', customer: 'Example Corp.', issuedAt: '2025-01-10', expiresAt: '2099-01-09',
        keyId: 'kimp', file: 'C:\\keys\\issued\\L-2025-0001-example-corp.lic', sha256: 'abcdef012345', signedAt: '2025-01-10T10:00:00+08:00', ...o });
    const original = `${core.REGISTRY_HEADER}${row({})}\n${row({ licenseId: 'L-2025-0002', expiresAt: '— (format 1, no expiry)' })}\n| L-2025-0003 | broken |\n`;
    fs.writeFileSync(reg, original);
    assert.equal(run('L-2026-0001', 'example corp.'), 0);
    const logged = console.log.mock.calls.map((c) => c.arguments[0]);
    assert.ok(logged.some((l) => /^Imported 2 license\(s\) from .+reg\.md into .+license-issuer\.db \(backup: .+reg\.md\.bak-\d{8}-\d{6}\)\.$/.test(l)), logged.join('\n'));
    assert.ok(console.error.mock.calls.some((c) => /Not imported, line 7 \(unreadable\): \| L-2025-0003 \| broken \|/.test(c.arguments[0])),
        console.error.mock.calls.map((c) => c.arguments[0]).join('\n'));
    assert.ok(logged.includes('Issued L-2026-0001 to "Example Corp."')); // the existing customer's name
    const backups = fs.readdirSync(dir).filter((f) => /^reg\.md\.bak-\d{8}-\d{6}$/.test(f));
    assert.equal(backups.length, 1);
    assert.equal(fs.readFileSync(path.join(dir, backups[0]), 'utf8'), original);
    const text = fs.readFileSync(reg, 'utf8');
    assert.match(text, /^<!-- Generated by license-issuer/);
    assert.match(text, /\| L-2025-0002 \| Example Corp\. \| Paid \| 2025-01-10 \| — \|  \| Format 1 \(invalid\) \|/);
    withStore(dir, (store) => {
        assert.deepEqual(store.listLicenses({ sort: 'id' }).map((l) => [l.licenseId, l.format, l.isRenewal]),
            [['L-2025-0001', 2, false], ['L-2025-0002', 1, true], ['L-2026-0001', 2, true]]);
        assert.equal(store.importRecord().imported, 2);
    });
    // never twice
    assert.equal(run('L-2026-0002', 'B'), 0);
    assert.equal(fs.readdirSync(dir).filter((f) => /\.bak-/.test(f)).length, 1);
    withStore(dir, (store) => assert.equal(store.licenseCount(), 4));
});

test('a generated registry with an empty database (wrong --db) is refused and left unchanged', (t) => {
    const { dir, reg, run } = setup(t, 'kgen');
    assert.equal(run('L-2026-0001', 'A'), 0);
    const before = fs.readFileSync(reg, 'utf8');
    assert.equal(run('L-2026-0002', 'B', ['--db', path.join(dir, 'empty.db')]), 1);
    assert.match(console.error.mock.calls.at(-1).arguments[0], /was generated from a license-issuer database, but the database .+empty\.db has no licenses/);
    assert.equal(fs.readFileSync(reg, 'utf8'), before);
    assert.equal(fs.existsSync(path.join(dir, 'L-2026-0002.lic')), false);
});
