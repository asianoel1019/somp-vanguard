// The Markdown registry (issued-licenses.md) as a generated, read-only copy of the database, and the one-time import of
// a registry written by earlier versions (CLI rows: License ID | Customer | Issued | Expires | Key | File | SHA-256 | Signed at).
const fs = require('fs');
const path = require('path');
const core = require(path.join(__dirname, '..', '..', '..', 'scripts', 'licenseIssuerCore'));
const R = require('./rules');

const { StoreError } = R;
const MARKER = '<!-- Generated by license-issuer from license-issuer.db. Do not edit by hand. -->';
const TITLE = '# SOMP Vanguard 已簽發授權登記表';
const COLUMNS = ['License ID', 'Customer', 'Type', 'Issued', 'Expires', 'Sales', 'Status', 'File', 'SHA-256', 'Signed at'];
const REASON_TEXT = { replaced: 'replaced', terminated: 'terminated', issued_in_error: 'issued in error', other: 'other' };

/** Whether a registry text was generated by license-issuer (its first line is the marker). */
const isGenerated = (text) => String(text || '').replace(/^\uFEFF/, '').startsWith('<!-- Generated by license-issuer');

/** The database ID a generated registry names ('' when it names none). */
function generatedBy(text) {
    const head = String(text || '').split(/\r?\n/).slice(0, 3).join('\n');
    const m = /^<!-- Database ID: ([0-9a-f]*) -->$/m.exec(head);
    return m ? m[1] : '';
}

/** The Status cell: the computed status; revoked ones with the reason (and the replacement). */
function statusCell(l) {
    if (!l.revokedAt) return l.status;
    if (l.revokeReason === 'replaced' && l.replacedByLicenseId) return `Revoked (replaced by ${l.replacedByLicenseId})`;
    return `Revoked (${REASON_TEXT[l.revokeReason] || l.revokeReason || 'no reason'})`;
}

/** The whole registry text from the database: every license in the order it was recorded. */
function renderRegistry(store) {
    const today = store.today();
    const lines = [
        MARKER,
        `<!-- Database ID: ${store.dbId()} -->`,
        TITLE,
        '',
        `狀態以 ${today} 為準（每次資料異動後重新產生）。`,
        '',
        `| ${COLUMNS.join(' | ')} |`,
        `|${COLUMNS.map(() => '---').join('|')}|`,
    ];
    for (const l of store.listLicenses({ sort: 'id' })) {
        const cells = [l.licenseId, l.licensedTo, l.type === 'trial' ? 'Trial' : 'Paid', l.issuedAt, l.expiresAt || '—', l.salesName || '',
            statusCell(l), l.filePath || '', l.sha12 || '', l.signedAt || ''];
        lines.push(`| ${cells.map(core.escapeCell).join(' | ')} |`);
    }
    return lines.join('\n') + '\n';
}

/**
 * Rewrites store.registryFile (temp file + rename). A file that exists, was not generated and was never imported is
 * left unchanged (error), so a hand-made registry is never lost. { ok, error (Error|null) }
 */
function writeRegistry(store) {
    const file = store.registryFile;
    let tmp = null;
    try {
        const cur = core.readRegistry(file);
        if (cur.error) throw cur.error;
        if (cur.text !== null && !isGenerated(cur.text) && !store.importRecord()) {
            throw new Error(`${file} was not generated by license-issuer and has not been imported; it was left unchanged`);
        }
        const other = cur.text !== null && isGenerated(cur.text) ? generatedBy(cur.text) : null;
        if (other && other !== store.dbId()) {
            throw new Error(`${file} was generated from another database (ID ${other}); it was left unchanged`);
        }
        const text = renderRegistry(store);
        tmp = `${file}.tmp-${process.pid}`;
        fs.writeFileSync(tmp, text);
        fs.renameSync(tmp, file);
        tmp = null;
        return { ok: true, error: null };
    } catch (e) {
        if (tmp) { try { fs.unlinkSync(tmp); } catch { /* not created */ } }
        return { ok: false, error: e instanceof Error ? e : new Error(String(e)) };
    }
}

/** Copies the registry to "<file>.bak-YYYYMMDD-HHmmss" (a -2, -3 ... suffix when that exists); returns the copy's path. */
function backupRegistryFile(file, date) {
    const base = `${file}.bak-${R.stamp(date)}`;
    for (let i = 1; ; i++) {
        const target = i === 1 ? base : `${base}-${i}`;
        try {
            fs.copyFileSync(file, target, fs.constants.COPYFILE_EXCL);
            return target;
        } catch (e) {
            if (!e || e.code !== 'EEXIST' || i >= 100) throw e;
        }
    }
}

/**
 * Imports a pre-database registry text (caller holds the registry lock; the database has no licenses). Every readable
 * row becomes a license: customer found or created by its exact name, type paid, no sales / amount / plan, format 2 when
 * Expires is a date else format 1 (status Format 1 (invalid)), renewal when the customer had an earlier paid license.
 * A license ID listed twice keeps its last row (the earlier ones are reported in duplicates).
 */
function importText(store, file, text) {
    const backup = backupRegistryFile(file, store.now());
    const parsed = core.parseRegistry(text);
    const unreadable = [...parsed.unreadable];
    const rows = [];
    for (const r of parsed.rows) {
        if (!r.customer) unreadable.push({ line: r.line, text: `${r.licenseId}: no customer name` });
        else rows.push(r);
    }
    unreadable.sort((a, b) => a.line - b.line);
    const last = new Map();
    rows.forEach((r, i) => last.set(r.licenseId.toUpperCase(), i));
    const keep = rows.filter((r, i) => last.get(r.licenseId.toUpperCase()) === i);
    const duplicates = rows.filter((r, i) => last.get(r.licenseId.toUpperCase()) !== i)
        .map((r) => ({ line: r.line, licenseId: r.licenseId, keptLine: rows[last.get(r.licenseId.toUpperCase())].line }));
    let customersCreated = 0;
    const at = store.stamp();
    store.tx(() => {
        const cid = new Map();
        for (const r of keep) {
            const found = store.db.prepare('SELECT id FROM customers WHERE name = ?').get(r.customer);
            if (found) cid.set(r, found.id);
            else { cid.set(r, store.insertCustomer({ name: r.customer })); customersCreated += 1; }
        }
        // renewal: an earlier paid license of the same customer (by issue date, then line)
        const order = [...keep].sort((a, b) => (a.issuedAt < b.issuedAt ? -1 : a.issuedAt > b.issuedAt ? 1 : a.line - b.line));
        const seen = new Set();
        const renewal = new Set();
        for (const r of order) {
            if (seen.has(cid.get(r))) renewal.add(r);
            seen.add(cid.get(r));
        }
        const ins = store.db.prepare(`INSERT INTO licenses (license_id, customer_id, licensed_to, type, format, issued_at, expires_at, is_renewal,
            file_path, sha12, signed_at, key_id, created_at) VALUES (?, ?, ?, 'paid', ?, ?, ?, ?, ?, ?, ?, ?, ?)`);
        for (const r of keep) {
            const format = R.isRealDate(r.expiresAt) ? 2 : 1;
            const res = ins.run(r.licenseId.toUpperCase(), cid.get(r), r.customer, format, r.issuedAt, format === 2 ? r.expiresAt : null,
                renewal.has(r) ? 1 : 0, r.file || null, r.sha256 ? r.sha256.toLowerCase() : null, r.signedAt || null, r.keyId || null, at);
            store.insertEvent(Number(res.lastInsertRowid), 'imported', {
                source: file, backup, line: r.line,
                row: { licenseId: r.licenseId, customer: r.customer, issuedAt: r.issuedAt, expiresAt: r.expiresAt, keyId: r.keyId, file: r.file, sha256: r.sha256, signedAt: r.signedAt },
            });
        }
        store.setImportRecord({ at, file, backup, imported: keep.length, customersCreated, unreadable, duplicates });
    });
    const reg = store.regenerateRegistry();
    return { status: 'imported', file, backup, imported: keep.length, customersCreated, unreadable, duplicates, registryError: reg.error };
}

/**
 * First use (web app start or CLI): when the database has no licenses and was never imported into, imports the existing
 * Markdown registry (backup first). Never imports twice. Returns { status, ... }:
 *   'done-before' (record) | 'no-registry' (no file, or this database's own generated copy) | 'not-empty' (the database already has licenses) |
 *   'imported' ({ file, backup, imported, customersCreated, unreadable: [{ line, text }], duplicates: [{ line, licenseId, keptLine }], registryError })
 * Throws StoreError: registry-unreadable (500), registry-generated (409: a registry generated by another (or an unnamed) database but an empty database —
 * wrong DB_FILE / --db, or a lost database: restore a backup), import-failed (500: backup or database write failed, nothing imported), locked (503).
 */
function importIfNeeded(store) {
    if (store.importRecord()) return { status: 'done-before', record: store.importRecord() };
    const file = store.registryFile;
    if (!file) return { status: 'no-registry' };
    return store.withRegistryLock(() => {
        if (store.importRecord()) return { status: 'done-before', record: store.importRecord() }; // another process was faster
        const reg = core.readRegistry(file);
        if (reg.error) {
            throw new StoreError('registry-unreadable', `Cannot read the registry ${file} (${reg.error.code || reg.error.message}).`, { status: 500 });
        }
        if (reg.text === null) return { status: 'no-registry' };
        if (store.licenseCount() > 0) return { status: 'not-empty' };
        if (isGenerated(reg.text)) {
            // this database's own copy (written by a sales / customer change before the first license): nothing to import
            const by = generatedBy(reg.text);
            if (by && by === store.dbId()) return { status: 'no-registry' };
            throw new StoreError('registry-generated', `The registry ${file} was generated from a license-issuer database, but the database ${store.file} `
                + 'has no licenses. Check DB_FILE (or --db), or restore the database from a backup. Nothing was changed.', { status: 409 });
        }
        try {
            return importText(store, file, reg.text);
        } catch (e) {
            if (e instanceof StoreError) throw e;
            throw new StoreError('import-failed', `Cannot import the registry ${file} (${e.code || e.message}). Nothing was imported.`, { status: 500 });
        }
    });
}

module.exports = { MARKER, TITLE, COLUMNS, isGenerated, generatedBy, statusCell, renderRegistry, writeRegistry, backupRegistryFile, importText, importIfNeeded };
